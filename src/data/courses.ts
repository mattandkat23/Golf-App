interface CourseDetails {
  phone?: string;
  website?: string;
  lat?: number;
  lng?: number;
  postalCode?: string;
  architect?: string;
  yearBuilt?: number;
  tees?: Course['tees'];
}
const DETAILS = courseDetails as Record<string, CourseDetails>;

export const SEED_COURSES: Course[] = SEEDS.map(([name, city, region, state]) => {
  const extra = DETAILS[`${name}|${city}`];
  return {
    name,
    city,
    region,
    state: state ?? 'TX', // every region but 'Other' is a Texas sub-region
    tees: extra?.tees ?? [],
    ...(extra && {
      phone: extra.phone,
      website: extra.website,
      lat: extra.lat,
      lng: extra.lng,
      postalCode: extra.postalCode,
      architect: extra.architect,
      yearBuilt: extra.yearBuilt,
    }),
  };
});

